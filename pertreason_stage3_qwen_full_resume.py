#!/usr/bin/env python3
"""PertReasonQA Stage 3 cloud runner: use unmodified Stage3LLMGeneration.process_sample.

Run on ModelScope GPU Notebook beside /mnt/workspace/pertreason_stage3.
No network calls are made except to the EXISTING local vLLM API on 127.0.0.1:8000.
Safety: validates source SHA256, unmodified Stage 3, checkpoints each sample,
imports previous pilot/batch results, skips previously attempted incomplete samples,
performs local snapshots. This is an EXECUTION WRAPPER, not author-supplied code.
"""
import argparse
import copy
import fcntl
import hashlib
import json
import os
import sys
import tarfile
import time
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path('/mnt/workspace/pertreason_stage3')
KG = ROOT / 'annotation_pipeline_kg'
DATA = ROOT / 'data' / 'annotations'
SOURCE = DATA / 'kg_original_n10000_seed42_stage2.jsonl'
PILOT = DATA / 'kg_qwen25_bf16_stage3_pilot1.jsonl'
BATCH10 = DATA / 'kg_qwen25_bf16_stage3_batch10.jsonl'
BATCH10_LOG = DATA / 'kg_qwen25_bf16_stage3_batch10_attempts.jsonl'
OUTPUT = DATA / 'kg_qwen25_bf16_stage3_full3668.jsonl'
JOURNAL = DATA / 'kg_qwen25_bf16_stage3_full3668_journal.jsonl'
MANIFEST = DATA / 'kg_qwen25_bf16_stage3_full3668_manifest.json'
ORDERED = DATA / 'kg_qwen25_bf16_stage3_full3668_ordered.jsonl'
SNAPSHOTS = DATA / 'qwen25_stage3_snapshots'
LOCK = DATA / '.qwen25_stage3_full3668.lock'
EXPECTED_INPUT_SHA256 = '11d42f40702769332a295e0945e10ffa33554f884bcd9c90e34c029266090695'
EXPECTED_STAGE3_SHA256 = '108920825d8876c2bf8ff5754f719263e12eaf6e79a0e220352730f92af56594'
EXPECTED_CONFIG_SHA256 = 'e479b211b57061f5b0e9ffa53d832d171de84be62b5be44ef8c9c19ff9dd3553'
MODEL = 'Qwen/Qwen2.5-7B-Instruct'
ENDPOINT = 'http://127.0.0.1:8000/v1'
TOTAL = 3668


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as fp:
        for b in iter(lambda: fp.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def read_jsonl(path):
    if not path.exists():
        return []
    with path.open('r', encoding='utf-8') as fp:
        return [json.loads(line) for line in fp if line.strip()]


def append_sync(fp, record):
    fp.write(json.dumps(record, ensure_ascii=False, separators=(',', ':')) + '\n')
    fp.flush()
    os.fsync(fp.fileno())


def atomic_json(path, value):
    tmp = path.with_name('.' + path.name + '.tmp')
    with tmp.open('w', encoding='utf-8') as fp:
        json.dump(value, fp, ensure_ascii=False, indent=2)
        fp.write('\n')
        fp.flush()
        os.fsync(fp.fileno())
    os.replace(tmp, path)


def utc_now():
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def validate_result(row, src):
    sid = row.get('id')
    if sid not in src:
        raise ValueError('Result ID not in Stage2: ' + str(sid))
    origin = src[sid]
    for key in ('input', 'basal_context', 'reasoning_paths'):
        if row.get(key) != origin.get(key):
            raise ValueError(f'Stage2 field {key} mismatch: {sid}')
    output = row.get('output')
    if not isinstance(output, dict):
        raise ValueError('Missing output: ' + str(sid))
    txt = output.get('reasoning_text')
    if not isinstance(txt, str) or not txt.strip():
        raise ValueError('Missing reasoning_text: ' + str(sid))
    first = origin['reasoning_paths'][0]
    if output.get('reasoning_id') != 0 or output.get('triplets_ref') != first['triplets'] or output.get('path_length') != first['length']:
        raise ValueError('Output path reference mismatch: ' + str(sid))


def load_source():
    if not SOURCE.is_file():
        raise SystemExit(f'Stage2 missing: {SOURCE}')
    sha = digest(SOURCE)
    if sha != EXPECTED_INPUT_SHA256:
        raise SystemExit(f'FAIL: Stage2 SHA256 different! {sha}')
    samples = read_jsonl(SOURCE)
    if len(samples) != TOTAL:
        raise SystemExit(f'FAIL: expected {TOTAL} Stage2 rows; got {len(samples)}')
    src = {s['id']: s for s in samples}
    if len(src) != TOTAL or not all(s.get('reasoning_paths') for s in samples):
        raise SystemExit('FAIL: duplicate IDs or empty paths')
    return samples, src


def history(src):
    # Legacy outputs already successfully generated by the author's method.
    imported = {}
    for path in (PILOT, BATCH10):
        for row in read_jsonl(path):
            validate_result(row, src)
            sid = row['id']
            if sid in imported and imported[sid] != row:
                raise SystemExit(f'Conflicting legacy CoT results: {sid}')
            imported[sid] = row
    return imported


def load_state(src):
    rows = read_jsonl(OUTPUT)
    saved = {}
    for row in rows:
        validate_result(row, src)
        sid = row['id']
        if sid in saved:
            raise SystemExit(f'Duplicate output ID: {sid}')
        saved[sid] = row
    events = read_jsonl(JOURNAL)
    attempted = {e['id'] for e in events if e.get('event') == 'started'}
    finished = {e['id'] for e in events if e.get('event') in ('saved', 'not_retained', 'exception')}
    if not attempted.issubset(set(src)):
        raise SystemExit('Journal contains unknown sample IDs')
    stale = attempted - finished - set(saved)
    return saved, events, attempted, stale


def ensure_manifest():
    stage3 = KG / 'stage3_llm_generation.py'
    cfg = KG / 'config.py'
    for item in (stage3, cfg):
        if not item.is_file():
            raise SystemExit(f'Original source missing: {item}')
    if digest(stage3) != EXPECTED_STAGE3_SHA256 or digest(cfg) != EXPECTED_CONFIG_SHA256:
        raise SystemExit('ERROR: Uploaded Stage3/config source differs from the verified original repository; stop for review.')
    meta = {
        'dataset_sha256': EXPECTED_INPUT_SHA256,
        'stage3_sha256': digest(stage3),
        'config_sha256': digest(cfg),
        'model_name': MODEL,
        'api_url': ENDPOINT,
        'run_type': 'original process_sample + checkpoint wrapper',
        'input_rows': TOTAL,
        'checkpoint_policy': 'fsync per record, snapshots every 100 processed',
        'initial_time_utc': utc_now(),
    }
    if MANIFEST.exists():
        recorded = json.loads(MANIFEST.read_text(encoding='utf-8'))
        for field in ('dataset_sha256','stage3_sha256','config_sha256','model_name','api_url','input_rows'):
            if recorded.get(field) != meta[field]:
                raise SystemExit(f'Manifest mismatch on {field}; do not overwrite outputs!')
    else:
        atomic_json(MANIFEST, meta)


def snapshot(index, reason):
    SNAPSHOTS.mkdir(parents=True, exist_ok=True)
    name = SNAPSHOTS / f'qwen_stage3_checkpoint_{index:04d}.tar.gz'
    tmp = name.with_name('.' + name.name + '.tmp')
    with tarfile.open(tmp, 'w:gz') as tf:
        for p in (OUTPUT, JOURNAL, MANIFEST):
            if p.is_file():
                tf.add(p, arcname=p.name)
    os.replace(tmp, name)
    print(f'[SNAPSHOT {reason}] {name} ({name.stat().st_size//1024} KiB)', flush=True)


def write_ordered(samples, saved):
    temp = ORDERED.with_name('.' + ORDERED.name + '.tmp')
    with temp.open('w', encoding='utf-8') as out:
        for s in samples:
            if s['id'] in saved:
                out.write(json.dumps(saved[s['id']], ensure_ascii=False, separators=(',', ':')) + '\n')
        out.flush()
        os.fsync(out.fileno())
    os.replace(temp, ORDERED)
    print(f'Ordered output: {ORDERED}; rows={len(saved)} sha256={digest(ORDERED)}', flush=True)


def status():
    samples, src = load_source()
    leg = history(src)
    saved, events, attempted, stale = load_state(src)
    success = Counter(e.get('event') for e in events)
    print('Input Stage2:', len(samples), ' | Source SHA:', EXPECTED_INPUT_SHA256)
    print('Pilot/batch10 successful:', len(leg), '| Main output successful:', len(saved))
    print('Events:', dict(success))
    print('Incomplete previous calls requiring review:', len(stale), sorted(stale)[:12])
    print('Run output:', OUTPUT)
    if OUTPUT.is_file():
        print('Output SHA256:', digest(OUTPUT))
    print('Snapshots:', len(list(SNAPSHOTS.glob('qwen_stage3_checkpoint_*.tar.gz'))) if SNAPSHOTS.exists() else 0)
    print('Only locally generated outputs are counted; the 3643 official CoT files are not reused.')


def run(max_new=0):
    DATA.mkdir(parents=True, exist_ok=True)
    with LOCK.open('a+') as lockfile:
        try:
            fcntl.flock(lockfile, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise SystemExit('ERROR: Another batch runner is active; refusing concurrent run')
        samples, src = load_source()
        ensure_manifest()
        legacy = history(src)
        saved, events, attempted, stale = load_state(src)
        if stale:
            print('WARNING: Incomplete requests found:', sorted(stale))
            print('They will NOT be auto-retried. Existing output remains safe.')
        # Import previously saved CoT from the 1-sample pilot and optional 10-sample test.
        fresh = [row for sid, row in legacy.items() if sid not in saved]
        if fresh:
            with OUTPUT.open('a', encoding='utf-8') as fp:
                for row in fresh:
                    append_sync(fp, row)
                    saved[row['id']] = row
            print('Imported existing original-method CoT rows:', len(fresh), flush=True)
        # Do not attempt previously logged incomplete/rejected requests automatically.
        blocked = set(attempted)
        for row in read_jsonl(BATCH10_LOG):
            if row.get('status') == 'request_started' and row['id'] not in saved:
                blocked.add(row['id'])
        print('Input:', len(samples), '| already saved:', len(saved), '| previous attempts skipped:', len(blocked - set(saved)), flush=True)
        remain = sum(1 for s in samples if s['id'] not in saved and s['id'] not in blocked)
        print('New requests to perform:', remain, '| model:', MODEL, flush=True)
        if not remain:
            write_ordered(samples, saved)
            snapshot(len(saved), 'no-new-work')
            return

        sys.path.insert(0, str(KG))
        from stage3_llm_generation import Stage3LLMGeneration
        from config import DEFAULT_LLM_BASE_URL, DEFAULT_LLM_MODEL, DEFAULT_TEMPERATURE, DEFAULT_MAX_TOKENS, MIN_REASONING_LENGTH, MAX_REASONING_LENGTH, BLACKLIST_KEYWORDS
        from openai import OpenAI
        if DEFAULT_LLM_MODEL != MODEL:
            raise SystemExit(f'Original config model mismatch: {DEFAULT_LLM_MODEL}')
        client = OpenAI(base_url=ENDPOINT, api_key='EMPTY', timeout=240, max_retries=0)
        try:
            available = [m.id for m in client.models.list()]
        except Exception as ex:
            raise SystemExit(f'Local vLLM not reachable: {type(ex).__name__}: {ex}')
        if MODEL not in available:
            raise SystemExit(f'Model mismatch: {available}')
        stage3 = Stage3LLMGeneration(
            llm_base_url=DEFAULT_LLM_BASE_URL, llm_model=DEFAULT_LLM_MODEL,
            temperature=DEFAULT_TEMPERATURE, max_tokens=DEFAULT_MAX_TOKENS,
            min_reasoning_length=MIN_REASONING_LENGTH, max_reasoning_length=MAX_REASONING_LENGTH,
            blacklist_keywords=BLACKLIST_KEYWORDS
        )
        stage3.client = client
        print(f'Starting original process_sample: temp={DEFAULT_TEMPERATURE}, max_tokens={DEFAULT_MAX_TOKENS}', flush=True)
        start_t = time.monotonic()
        count_new = 0
        rejected = 0
        streak_none = 0
        try:
            with OUTPUT.open('a', encoding='utf-8') as out, JOURNAL.open('a', encoding='utf-8') as journal:
                for sample in samples:
                    sid = sample['id']
                    if sid in saved or sid in blocked:
                        continue
                    # periodic health check before starting the next sample
                    if count_new % 25 == 0:
                        try:
                            assert MODEL in [m.id for m in client.models.list()]
                        except Exception as ex:
                            print(f'STOP: vLLM health check failed: {type(ex).__name__}: {ex}', flush=True)
                            break
                    append_sync(journal, {'utc': utc_now(), 'id': sid, 'event': 'started'})
                    attempted.add(sid)
                    try:
                        result = stage3.process_sample(copy.deepcopy(sample))
                    except Exception as ex:
                        append_sync(journal, {'utc': utc_now(), 'id': sid, 'event': 'exception', 'error_type': type(ex).__name__, 'error': str(ex)[:180]})
                        print(f'[{len(saved)}/{TOTAL}] STOP on exception {sid} {type(ex).__name__}: {str(ex)[:120]}', flush=True)
                        break
                    count_new += 1
                    if result is None:
                        rejected += 1
                        streak_none += 1
                        append_sync(journal, {'utc': utc_now(), 'id': sid, 'event': 'not_retained'})
                        print(f'[{len(saved)}/{TOTAL}] no result: {sid}, streak={streak_none}', flush=True)
                        if streak_none >= 5:
                            print('STOP: 5 consecutive no-result samples; check service and quality filtering. No auto-retry.', flush=True)
                            break
                    else:
                        try:
                            validate_result(result, src)
                        except Exception as ex:
                            append_sync(journal, {'utc': utc_now(), 'id': sid, 'event': 'exception', 'error_type': 'output_validation', 'error': str(ex)[:180]})
                            print(f'STOP: invalid output {sid}: {ex}', flush=True)
                            break
                        append_sync(out, result)
                        saved[sid] = result
                        append_sync(journal, {'utc': utc_now(), 'id': sid, 'event': 'saved', 'words': len(result['output']['reasoning_text'].split())})
                        streak_none = 0
                        if len(saved) <= 20 or count_new % 25 == 0:
                            print(f'[DONE {len(saved)}/{TOTAL}] {sid} words={len(result["output"]["reasoning_text"].split())} elapsed={time.monotonic()-start_t:.0f}s', flush=True)
                    if count_new % 100 == 0:
                        snapshot(len(saved), f'{count_new}-new-attempts')
                    if max_new and count_new >= max_new:
                        print('Reached --max-new requested limit', flush=True)
                        break
        except KeyboardInterrupt:
            print('Interrupted. Completed JSONL rows are fsync-saved. Any started-but-unsaved record will be skipped on resume.', flush=True)
        print('Run attempt count:', count_new, '| saved rows:', len(saved), '| not retained in this session:', rejected, flush=True)
        write_ordered(samples, saved)
        snapshot(len(saved), 'end-run')
        print('Output:', OUTPUT)
        print('Journal:', JOURNAL)
        print('SHA256:', digest(OUTPUT))
        now_events = read_jsonl(JOURNAL)
        fresh_attempted = {e['id'] for e in now_events if e.get('event') == 'started'}
        previous_attempted = {e['id'] for e in read_jsonl(BATCH10_LOG) if e.get('status') == 'request_started'}
        pending = len(set(src) - set(saved) - fresh_attempted - previous_attempted)
        if pending:
            print(f'INCOMPLETE: {pending} unattempted input samples remain. Resume using --run.', flush=True)
        else:
            print(f'COMPLETE FIRST PASS: {len(saved)} saved, {TOTAL-len(saved)} not saved/previously attempted.', flush=True)
        print('To resume or review: python -u /mnt/workspace/pertreason_stage3_qwen_full_resume.py --run or --status', flush=True)


def main():
    p = argparse.ArgumentParser(description='Large scale original PertReasonQA Stage3 Qwen2.5 BF16, checkpoint wrapper')
    group = p.add_mutually_exclusive_group(required=True)
    group.add_argument('--run', action='store_true', help='Generate all remaining samples, skip saved/prior attempted')
    group.add_argument('--status', action='store_true', help='Read-only progress overview')
    p.add_argument('--max-new', type=int, default=0, help='Optional limit for new generation attempts (0=all)')
    args = p.parse_args()
    if args.max_new < 0:
        p.error('max-new cannot be negative')
    if args.status:
        status()
    else:
        run(max_new=args.max_new)


if __name__ == '__main__':
    main()
